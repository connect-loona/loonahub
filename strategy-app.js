    async function soSubmitNewRun(){
      var brandId = document.getElementById("so-new-brand").value;
      var month = document.getElementById("so-new-month").value;
      var errEl = document.getElementById("so-new-run-error");
      var btn = document.getElementById("so-new-run-submit");
      if(errEl){ errEl.style.display="none"; }
      if(!month){ if(errEl){ errEl.textContent="Pick a month."; errEl.style.display="block"; } return; }
      if(btn){ btn.disabled=true; btn.textContent="Starting…"; }
      try {
        var res = await fetch("/.netlify/functions/strategy-run-start", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ brandId: brandId, month: month, actor: currentUser || "Unknown" }),
        });
        var data = await res.json().catch(function(){ return {}; });
        if(!res.ok) throw new Error((data.error||"Could not start this run.")+(data.reason?" — "+data.reason:""));
        soCloseNewRunModal();
        window.soOpenRun(data.runId);
      } catch(e) {
        if(errEl){ errEl.textContent = e.message || String(e); errEl.style.display="block"; }
      } finally {
        if(btn){ btn.disabled=false; btn.textContent="Start research"; }
      }
    }

    // Archives a run — mainly for clearing out stale/duplicate test or abandoned runs,
    // which otherwise permanently block starting a fresh one for that brand+month
    // (strategy-run-start.js's own 409 "already an active run" check treats a listed run as
    // live until it's either approved all the way through or archived). Unlike the old
    // outright Delete this used to be, archiving is reversible: the run drops out of the
    // active list and the duplicate-run check, but nothing about it is touched or lost, and
    // it can be restored from the Archived view at any time. Direct Firebase write, same as
    // the per-asset lock toggle — no backend logic needed.
    async function soArchiveRun(runId){
      if(!_db) return;
      var run = (window._soRunsCache || {})[runId];
      var label = run ? (soBrandName(run.brandId)+' · '+monthLabel(run.month)) : runId;
      if(!confirm('Archive this run ('+label+')? It moves to the Archived view and won\'t block starting a new run for the same brand + month. You can restore it anytime.')) return;
      var reason = prompt('Optional: why are you archiving this?') || "";
      await _db.ref("strategy_runs/"+runId).update({
        archivedAt: new Date().toISOString(),
        archivedBy: currentUser || "Unknown",
        archiveReason: reason || null,
      });
    }

    async function soRestoreRun(runId){
      if(!_db) return;
      var run = (window._soRunsCache || {})[runId];
      var label = run ? (soBrandName(run.brandId)+' · '+monthLabel(run.month)) : runId;
      if(!confirm('Restore this run ('+label+')? It reappears in the active list.')) return;
      await _db.ref("strategy_runs/"+runId).update({ archivedAt: null, archivedBy: null, archiveReason: null });
    }

    // The old outright-Delete behavior, kept as a deliberately harder-to-reach exceptional
    // action — only offered from the Archived view, and gated behind typing the run's exact
    // label back rather than a plain confirm(), matching the same pattern Hub already uses
    // for its other irreversible deletes (see deleteMemberPermanently). The run's own
    // history in strategy_stage_versions/strategy_activity is left behind untouched —
    // orphaned but harmless, never referenced by anything once the run itself is gone.
    async function soPurgeRun(runId){
      if(!_db) return;
      var run = (window._soRunsCache || {})[runId];
      var label = run ? (soBrandName(run.brandId)+' · '+monthLabel(run.month)) : runId;
      var typed = prompt('This PERMANENTLY deletes "'+label+'" — it cannot be restored.\n\nType the run\'s label exactly to confirm:\n\n'+label);
      if(typed === null) return;
      if(typed !== label){ alert('Didn\'t match — nothing was deleted.'); return; }
      await _db.ref("strategy_runs/"+runId).remove();
    }

