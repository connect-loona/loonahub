    // The "front" of the pipeline — the first stage in STAGE_ORDER that isn't approved yet.
    // Once every stage is approved, this returns the last stage (deck-builder) so the UI
    // still has something concrete to point at.
    function currentStageOf(run){
      if(!run || !run.stages) return STAGE_ORDER[0];
      for(var i=0;i<STAGE_ORDER.length;i++){
        var s = STAGE_ORDER[i];
        var st = run.stages[s];
        if(!st || st.status !== "approved") return s;
      }
      return STAGE_ORDER[STAGE_ORDER.length-1];
    }

