    async function soSubmitBrandForm(brandIdArg){
      var isNew = brandIdArg === "__new__";
      var errEl = document.getElementById("so-bf-error");
      var btn = document.getElementById("so-bf-submit");
      if(errEl){ errEl.style.display="none"; errEl.textContent=""; }

      var id = document.getElementById("so-bf-id").value.trim();
      if(!/^[a-z0-9-]+$/.test(id)){
        if(errEl){ errEl.textContent="Brand id must be lowercase letters, numbers or hyphens."; errEl.style.display="block"; }
        return;
      }

      var audiences = Array.from(document.querySelectorAll("#so-audience-rows .so-row")).map(function(row){
        return {
          id: row.querySelector('[data-field="id"]').value.trim(),
          description: row.querySelector('[data-field="description"]').value.trim(),
          buyingSituation: row.querySelector('[data-field="buyingSituation"]').value.trim(),
          trigger: row.querySelector('[data-field="trigger"]').value.trim(),
        };
      }).filter(function(a){ return a.id; });

      var pillars = Array.from(document.querySelectorAll("#so-pillar-rows .so-row")).map(function(row){
        return {
          id: row.querySelector('[data-field="id"]').value.trim(),
          name: row.querySelector('[data-field="name"]').value.trim(),
          description: row.querySelector('[data-field="description"]').value.trim(),
          targetShare: parseFloat(row.querySelector('[data-field="targetShare"]').value) || 0,
        };
      }).filter(function(p){ return p.id; });

      var advanced;
      try {
        advanced = JSON.parse(document.getElementById("so-bf-advanced").value || "{}");
      } catch(e) {
        if(errEl){ errEl.textContent="The Advanced JSON isn't valid: "+e.message; errEl.style.display="block"; }
        return;
      }

      var config = {
        schemaVersion: "1.0",
        id: id,
        name: document.getElementById("so-bf-name").value.trim(),
        category: document.getElementById("so-bf-category").value.trim(),
        market: splitCsv(document.getElementById("so-bf-market").value),
        aspirationalMarkets: splitCsv(document.getElementById("so-bf-aspirational").value),
        website: document.getElementById("so-bf-website").value.trim() || null,
        driveFolderUrl: document.getElementById("so-bf-drive").value.trim() || null,
        oneLineTruth: document.getElementById("so-bf-truth").value.trim(),
        deliverables: {
          reel: parseInt(document.getElementById("so-bf-reel").value, 10) || 0,
          carousel: parseInt(document.getElementById("so-bf-carousel").value, 10) || 0,
          static: parseInt(document.getElementById("so-bf-static").value, 10) || 0,
          confirmed: document.getElementById("so-bf-confirmed").checked,
        },
        voice: {
          descriptors: splitCsv(document.getElementById("so-bf-descriptors").value),
          principles: splitLines(document.getElementById("so-bf-principles").value),
          bannedWords: splitCsv(document.getElementById("so-bf-bannedwords").value),
          bannedMoves: splitLines(document.getElementById("so-bf-bannedmoves").value),
          emojiRule: document.getElementById("so-bf-emojirule").value.trim(),
          languageRule: document.getElementById("so-bf-languagerule").value.trim(),
        },
        audiences: audiences,
        visual: {
          feel: splitCsv(document.getElementById("so-bf-feel").value),
          palette: splitCsv(document.getElementById("so-bf-palette").value),
          principles: splitLines(document.getElementById("so-bf-visprinciples").value),
          avoid: splitLines(document.getElementById("so-bf-visavoid").value),
        },
        pillars: pillars,
        competitors: splitCsv(document.getElementById("so-bf-competitors").value),
        knownUnknowns: splitLines(document.getElementById("so-bf-unknowns").value),
        portfolios: advanced.portfolios || [],
        claimRules: advanced.claimRules || [],
        copyStructure: advanced.copyStructure || null,
        sourceVectorStoreIds: advanced.sourceVectorStoreIds || [],
        canva: advanced.canva || soDefaultBrandTemplate().canva,
      };

      if(btn){ btn.disabled=true; btn.textContent="Saving…"; }
      try {
        var res = await fetch("/.netlify/functions/strategy-brand-save", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ brandId: id, config: config }),
        });
        var data = await res.json().catch(function(){ return {}; });
        if(!res.ok){
          var msg = data.error || "Could not save this brand.";
          if(Array.isArray(data.issues) && data.issues.length){
            msg += "\n\n" + data.issues.map(function(i){ return "• "+i.path+": "+i.message; }).join("\n");
          }
          throw new Error(msg);
        }
        window.soOpenBrandList();
      } catch(e) {
        if(errEl){ errEl.textContent = e.message || String(e); errEl.style.display="block"; }
      } finally {
        if(btn){ btn.disabled=false; btn.textContent="Save brand"; }
      }
    }

